export function buildDefaultBombeDeck(count = 14): Card[] {
  const shuffled = [...CATS].sort(() => Math.random() - 0.5).slice(0, count);
  return shuffled.map((c, idx) => ({
    id: `bombe-default-${idx}-${c.t.slice(0, 8)}`,
    mode: "bombe" as const,
    texte: c.t,
    gage: DEFAULT_BOMBE_GAGE,
    alternative: "",
    intensite: c.i,
    tags_theme: [],
    packs: [],
    premium: false,
    age18: c.i >= 4,
    actif: true,
    source: "builtin",
    version: 1,
  }));
}
